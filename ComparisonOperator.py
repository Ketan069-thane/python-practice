#Comparison Operator
# 1st is Greater Than and Greater than equal Operator
x = 23
y = 33
#It prints Boolean Values like True and False
print("Is X is Greater than Y: ", x >= y)

# 2nd is Smaller and Smaller than equal operator
a = 66
b = 33
print("Is A is smaller than or equal to B" , a <= b)

# 3rd is Equal to operator
c = 99
d = 99
print("Is C is equal to D", c == d)

# 4th is Not Equal to Operator
e = 56
f = 55
print("Is E and F are not equal:-" , e != f)

