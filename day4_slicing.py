name ="Ketan"
print(name[0:3]) # Accessing first three characters
print(name[2:5]) # Accessing characters from index 2 to 4
print(name[:4])  # Accessing first four characters  
print(name[2:])  # Accessing characters from index 2 to end
print(name[-1])  # Accessing last character
print(name[-3:]) # Accessing last three characters
print(name[::-1]) # Reversing the string
