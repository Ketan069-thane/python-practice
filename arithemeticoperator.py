a = int(input("Enter 1st Number :-"))
b = int(input("Enter 2nd Number :-"))
# For Addition Operator
print("The addition of the 2 numbers are :- " , a + b)
#For Substraction Operator
print("The substraction of the 2 numbers are :- ", a - b)
#For Multiplication Operator
print("The product of the 2 numbers are :- ", a * b)
#For Division Operator
print("The division of the 2 numbers are :-", a / b)
#For Float Division (//) Opeartor
print("The Float Division of the 2 numbers are :- ", a // b)
#For Modulus Operator
print("The Modulus of the 2 numbers are :-", a % b)
#For Float Multiplication Operator
print("The Float Mutliplication of the 2 numbers are :-" , a ** b)
